// ── Helpers ──────────────────────────────────────────────────────────

function h(text, level = HeadingLevel.HEADING_1) {
  return new Paragraph({ heading: level, children: [new TextRun({ text, font: "Microsoft YaHei" })] });
}

function p(text, opts = {}) {
  return new Paragraph({
    spacing: { after: 120 },
    ...opts,
    children: [new TextRun({ text, font: "Microsoft YaHei", size: 21, ...opts })]
  });
}

function bp(text) {
  return p(text, { bold: true });
}

function empty() {
  return new Paragraph({ spacing: { after: 60 }, children: [] });
}

function cell(text, opts = {}) {
  const lines = Array.isArray(text) ? text : [text];
  const children = lines.map(t => new Paragraph({
    children: [new TextRun({ text: t, font: "Microsoft YaHei", size: 18, ...opts })]
  }));
  return new TableCell({
    width: opts.cellWidth ? { size: opts.cellWidth, type: WidthType.DXA } : undefined,
    shading: opts.shading ? { fill: opts.shading, type: ShadingType.CLEAR } : undefined,
    verticalAlign: "center",
    children,
  });
}

function hcell(text, width) {
  return cell(text, { bold: true, shading: "D9E2F3", cellWidth: width });
}

function tbl(headers, rows, colWidths) {
  const totalWidth = colWidths.reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: totalWidth, type: WidthType.DXA },
    columnWidths: colWidths,
    rows: [
      new TableRow({ children: headers.map((hdr, i) => hcell(hdr, colWidths[i])) }),
      ...rows.map(row => new TableRow({
        children: row.map((c, i) => cell(c, { cellWidth: colWidths[i] }))
      }))
    ]
  });
}

function bul(text) {
  return new Paragraph({
    spacing: { after: 60 },
    bullet: { level: 0 },
    indent: { left: 720 },
    children: [new TextRun({ text, font: "Microsoft YaHei", size: 21 })]
  });
}

